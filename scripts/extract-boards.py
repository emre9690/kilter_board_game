#!/usr/bin/env python3
"""Regenerate src/js/boards-data.js from the Kilter app database.

The database ships with https://github.com/1-max-1/fake_kilter_board
(fakeAuroraBoard_processing/data/database.db).

Usage: python3 scripts/extract-boards.py path/to/database.db
"""
import sqlite3
import sys
from pathlib import Path

ORIGINAL, HOMEWALL = 1, 7
# Holes below these heights sit on the kickboard (Original: product size "without kickboard" starts at 12;
# Homewall: the Mainline/Auxiliary Kickboard sets are at y = -4 / -8).
KICKBOARD_TOP = {ORIGINAL: 12, HOMEWALL: 0}
# Product size id -> name shown in the board picker (the app's own names are inconsistent).
NAMES = {
    10: 'Original 12×12 with kickboard',
    27: 'Original 12×12 no kickboard',
    7: 'Original 12×14 Commercial',
    28: 'Original 16×12 Super Wide',
    8: 'Original 8×12 Home',
    14: 'Original 7×10 Small',
    17: 'Homewall 7×10 Full Ride',
    18: 'Homewall 7×10 Mainline',
    19: 'Homewall 7×10 Auxiliary',
    21: 'Homewall 10×10 Full Ride',
    22: 'Homewall 10×10 Mainline',
    23: 'Homewall 8×12 Full Ride',
    24: 'Homewall 8×12 Mainline',
    25: 'Homewall 10×12 Full Ride',
    26: 'Homewall 10×12 Mainline',
}
PER_LINE = 20


def main(db_path):
    db = sqlite3.connect(db_path)
    out = [
        '// Generated by scripts/extract-boards.py from the Kilter app database. Do not edit by hand.',
        '// leds: [ledPosition, holeX, holeY] in Kilter board units (y up). kickboardTop: holes below are on the kickboard.',
        'export const BOARDS = [',
    ]
    for size_id, name in NAMES.items():
        (product_id,) = db.execute('SELECT product_id FROM product_sizes WHERE id = ?', (size_id,)).fetchone()
        leds = db.execute(
            'SELECT l.position, h.x, h.y FROM leds l JOIN holes h ON h.id = l.hole_id '
            'WHERE l.product_size_id = ? ORDER BY l.position',
            (size_id,),
        ).fetchall()
        top = KICKBOARD_TOP[product_id]
        kickboard = top if any(y < top for _, _, y in leds) else None
        family = 'original' if product_id == ORIGINAL else 'homewall'
        out.append(f"  {{ id: {size_id}, family: '{family}', name: '{name}', kickboardTop: {'null' if kickboard is None else kickboard}, leds: [")
        cells = [f'[{p},{x},{y}]' for p, x, y in leds]
        for i in range(0, len(cells), PER_LINE):
            out.append('    ' + ','.join(cells[i : i + PER_LINE]) + ',')
        out.append('  ] },')
    out.append('];')
    target = Path(__file__).resolve().parent.parent / 'src' / 'js' / 'boards-data.js'
    target.write_text('\n'.join(out) + '\n')
    print(f'Wrote {target} ({len(NAMES)} boards)')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
