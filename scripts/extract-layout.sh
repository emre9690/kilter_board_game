#!/usr/bin/env bash
# Regenerates src/js/board-data.js from the Kilter app database bundled in
# https://github.com/1-max-1/fake_kilter_board (fakeAuroraBoard_processing/data/database.db).
#
# Usage: scripts/extract-layout.sh path/to/database.db [product_size_id]
#   product_size_id 10 = Kilter Board Original, 12 x 12 with kickboard (default)
#   other Original sizes: 7 = 12x14, 8 = 8x12, 14 = 7x10, 27 = 12x12 no kickboard, 28 = 16x12
set -euo pipefail

DB="${1:?path to Kilter database.db required}"
SIZE="${2:-10}"
OUT="$(dirname "$0")/../src/js/board-data.js"

{
  echo "// Generated by scripts/extract-layout.sh (product_size_id=$SIZE). Do not edit by hand."
  echo "// Each entry is [ledPosition, holeX, holeY] in Kilter board units (inches-ish, y up)."
  echo "export const PRODUCT_SIZE_ID = $SIZE;"
  echo "export const LEDS = ["
  sqlite3 -separator ',' "$DB" \
    "SELECT l.position, h.x, h.y FROM leds l JOIN holes h ON h.id = l.hole_id
     WHERE l.product_size_id = $SIZE ORDER BY l.position" |
    awk '{ printf "[%s],", $0; if (NR % 12 == 0) printf "\n" } END { printf "\n" }' |
    sed 's/^/  /'
  echo "];"
} > "$OUT"

echo "Wrote $OUT"
