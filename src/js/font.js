// Score as a bitmap that fits the board: 2x scale when it fits, otherwise stretched vertically only.
export function numberBitmap(value, maxWidth = 17) {
  const digits = String(Math.max(0, Math.floor(value))).split('');
  const sx = digits.length * 7 - 1 <= maxWidth ? 2 : 1;
  const sy = 2;
  const rows = [];
  for (let r = 0; r < 5; r++) {
    const line = digits
      .map((d) => [...SMALL_DIGITS[d][r]].map((ch) => ch.repeat(sx)).join(''))
      .join('.');
    for (let i = 0; i < sy; i++) rows.push(line);
  }
  return rows;
}
